"""Generate dbt files (sources, staging models, properties and tests) from source metadata.

Everything written here is derived from metadata/sources/*.yml. Edit the metadata, never the
generated files; `python -m hearth generate --check` fails if they are out of date.

The bronze table (written by the loader) has the file's ID columns as strings, a
`_rescued_data` JSON string holding every period column, plus `_source_file` and `_loaded_at`.
Staging explodes that JSON, so new periods in later files need no code or metadata change.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from hearth.metadata import METADATA_DIR, Source, UniqueRule, load_all

ROOT = Path(__file__).resolve().parent.parent
STAGING_DIR = ROOT / "models" / "staging"
BRONZE_SCHEMA = "bronze"
HEADER = "GENERATED by `python -m hearth generate` from metadata/sources/{sid}.yml. Do not edit."


def spark_regex(pattern: str) -> str:
    """Spark SQL string literals treat backslash as an escape, so double it."""
    return pattern.replace("\\", "\\\\").replace("'", "''")


def _dump(data: dict, header: str) -> str:
    body = yaml.safe_dump(data, sort_keys=False, width=100, allow_unicode=True)
    return f"# {header}\n{body}"


def _expr(source: Source, column) -> str:
    if column.from_ is None:
        raw = "_period" if column.name == source.shape.value_columns.month_column else "_value"
    else:
        raw = column.from_
    return f"cast(nullif(trim({raw}), '') as {column.type}) as {column.name}"


def render_staging_sql(source: Source) -> str:
    vc = source.shape.value_columns
    select = ",\n        ".join(_expr(source, c) for c in source.columns)
    return f"""-- {HEADER.format(sid=source.id)}
-- {source.title}: one row per {source.grain.geography} and {source.grain.time}.
-- Uses the most recent load only; the wide file is unpivoted from its rescued-data JSON.
with src as (
    select * from {{{{ source('{BRONZE_SCHEMA}', '{source.id}') }}}}
),

latest_load as (
    select * from src
    where _loaded_at = (select max(_loaded_at) from src)
),

unpivoted as (
    select
        l.*,
        p.key as _period,
        p.value as _value
    from latest_load as l
    lateral view explode(from_json(l._rescued_data, 'map<string,string>')) p as key, value
    where p.key rlike '{spark_regex(vc.pattern)}'
),

renamed as (
    select
        {select},
        _source_file,
        _loaded_at
    from unpivoted
)

select * from renamed
"""


def _column_tests(source: Source, column) -> list:
    tests: list = []
    if not column.nullable:
        tests.append("not_null")
    if column.pattern:
        expr = f"rlike '{spark_regex(column.pattern)}'"
        tests.append({"dbt_utils.expression_is_true": {"arguments": {"expression": expr}}})
    for rule in source.rules:
        if rule.kind == "range" and rule.column == column.name:
            args = {
                k: v for k, v in (("min_value", rule.min), ("max_value", rule.max)) if v is not None
            }
            tests.append(
                {
                    "dbt_utils.accepted_range": {
                        "arguments": args,
                        "config": {"severity": rule.severity},
                    }
                }
            )
    return tests


def render_staging_yml(sources: dict[str, Source]) -> str:
    models = []
    for source in sources.values():
        columns = []
        for col in source.columns:
            entry: dict = {"name": col.name}
            if col.description:
                entry["description"] = col.description
            if col.units:
                entry["config"] = {"meta": {"units": col.units}}
            tests = _column_tests(source, col)
            if tests:
                entry["data_tests"] = tests
            columns.append(entry)
        model: dict = {
            "name": f"stg_{source.id}",
            "description": (
                f"{source.title}, one row per {source.grain.geography} and {source.grain.time}."
            ),
            "config": {"meta": {"owner": source.owner.name, "source_id": source.id}},
            "columns": columns,
        }
        unique = [
            {
                "dbt_utils.unique_combination_of_columns": {
                    "arguments": {"combination_of_columns": rule.columns},
                    "config": {"severity": rule.severity},
                }
            }
            for rule in source.rules
            if isinstance(rule, UniqueRule)
        ]
        if unique:
            model["data_tests"] = unique
        models.append(model)
    return _dump(
        {"version": 2, "models": models}, "GENERATED by `python -m hearth generate`. Do not edit."
    )


def render_sources_yml(sources: dict[str, Source]) -> str:
    tables = []
    for source in sources.values():
        tables.append(
            {
                "name": source.id,
                "description": f"{source.title}. Landed as-is by the loader (all text).",
                "config": {
                    "loaded_at_field": "_loaded_at",
                    "freshness": {
                        "warn_after": {"count": source.freshness.warn_after_days, "period": "day"},
                        "error_after": {
                            "count": source.freshness.error_after_days,
                            "period": "day",
                        },
                    },
                    "meta": {
                        "owner": source.owner.name,
                        "refresh_cadence": source.refresh.cadence,
                        "attribution": source.license.attribution,
                        "terms_url": source.license.terms_url,
                        "redistribution": source.license.redistribution,
                    },
                },
            }
        )
    data = {
        "version": 2,
        "sources": [
            {
                "name": BRONZE_SCHEMA,
                "database": "{{ env_var('DATABRICKS_CATALOG', 'workspace') }}",
                "schema": BRONZE_SCHEMA,
                "tables": tables,
            }
        ],
    }
    return _dump(data, "GENERATED by `python -m hearth generate`. Do not edit.")


def expected_files(
    metadata_dir: Path = METADATA_DIR, out_dir: Path = STAGING_DIR
) -> dict[Path, str]:
    sources = load_all(metadata_dir)
    files = {out_dir / f"stg_{sid}.sql": render_staging_sql(s) for sid, s in sources.items()}
    files[out_dir / "_sources.yml"] = render_sources_yml(sources)
    files[out_dir / "_staging.yml"] = render_staging_yml(sources)
    return files


def stale_files(files: dict[Path, str], out_dir: Path = STAGING_DIR) -> list[Path]:
    stale = [
        p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    wanted = {p.name for p in files}
    stale += [p for p in out_dir.glob("stg_*.sql") if p.name not in wanted]  # profile removed
    return stale


def write_files(files: dict[Path, str]) -> None:
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
